// Generate browser types from the backend's GraphQL-decorated DTOs.
// Usage: node scripts/sync-backend-contracts.cjs [backend repository]
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const prettier = require('prettier');
const formatOptions = JSON.parse(fs.readFileSync(path.resolve('.prettierrc'), 'utf8'));
const writeGenerated = (file, text) =>
	fs.writeFileSync(file, prettier.format(text, { ...formatOptions, filepath: file }));
const source = path.resolve(process.argv[2] || '../Hotelia', 'apps/hotelia-api/src/libs');
const destination = path.resolve('libs/types');
fs.mkdirSync(destination, { recursive: true });
const parse = (file) => ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
const enums = [];
const enumModules = [];
const enumDestination = path.resolve('libs/enums');
fs.mkdirSync(enumDestination, { recursive: true });
for (const name of [
	'member',
	'hotel',
	'room',
	'booking',
	'like',
	'common',
	'comment',
	'board-article',
	'notice',
	'notification',
	'payment',
]) {
	const file = path.join(source, 'enums', `${name}.enum.ts`);
	const tree = parse(file);
	const start = enums.length;
	for (const node of tree.statements) {
		if (ts.isEnumDeclaration(node) && node.name.text !== 'Message') {
			// GraphQL sends enum names, even when Nest/Mongoose uses numeric values internally.
			const numeric = node.members.some(
				(member) =>
					member.initializer &&
					(ts.isNumericLiteral(member.initializer) || ts.isPrefixUnaryExpression(member.initializer)),
			);
			enums.push(
				numeric
					? `export enum ${node.name.text} {\n${node.members
							.map((member) => `\t${member.name.getText(tree)} = '${member.name.getText(tree)}',`)
							.join('\n')}\n}`
					: node.getText(tree),
			);
		}
	}
	writeGenerated(
		path.join(enumDestination, `${name}.enum.ts`),
		'// Generated by scripts/sync-backend-contracts.cjs. Do not edit by hand.\n' +
			enums.slice(start).join('\n\n') +
			'\n',
	);
	enumModules.push(`export * from './${name}.enum';`);
}
const enumNames = enums.map((text) => text.match(/enum (\w+)/)[1]);
fs.writeFileSync(
	path.join(enumDestination, 'index.ts'),
	'// Generated enum exports.\n' + enumModules.join('\n') + '\n',
);
const files = [
	'auth/token-pair.ts',
	'member/member.ts',
	'member/member-public.ts',
	'member/member.input.ts',
	'member/member.update.ts',
	'follow/follow.ts',
	'follow/follow.input.ts',
	'like/like.ts',
	'like/favorite-result.ts',
	'like/favorites.inquiry.ts',
	'view/visited.inquiry.ts',
];
for (const folder of ['hotel', 'room', 'booking', 'comment', 'board-article', 'support', 'notification', 'payment']) {
	for (const file of fs.readdirSync(path.join(source, 'dto', folder)).sort()) {
		if (file.endsWith('.ts')) files.push(`${folder}/${file}`);
	}
}
const interfaces = [];
const interfaceFiles = [];
for (const file of files) {
	const tree = parse(path.join(source, 'dto', file));
	for (const node of tree.statements) {
		if (!ts.isClassDeclaration(node) || !node.name) continue;
		const input = node.decorators?.some((decorator) => decorator.getText(tree).startsWith('@InputType'));
		const fields = [];
		for (const member of node.members) {
			if (!ts.isPropertyDeclaration(member)) continue;
			const field = member.decorators?.find((decorator) => decorator.getText(tree).startsWith('@Field('));
			if (!field || !member.type) continue;
			const nullable = /nullable:\s*true/.test(field.getText(tree));
			const optional = nullable || (input && /defaultValue:/.test(field.getText(tree)));
			let type = member.type
				.getText(tree)
				.replace(/(?:Types\.|mongoose\.)?ObjectId\b/g, 'string')
				.replace(/\bDate\b/g, 'string');
			if (nullable && !input && !/\bnull\b/.test(type)) type += ' | null';
			fields.push(`\t${member.name.getText(tree)}${optional ? '?' : ''}: ${type};`);
		}
		const parent = node.heritageClauses?.flatMap((clause) =>
			clause.types.map((type) => {
				const expression = type.expression;
				if (ts.isCallExpression(expression) && expression.expression.getText(tree) === 'OmitType') {
					const keys = expression.arguments[1]
						.getText(tree)
						.replace(/\s+as const$/, '')
						.slice(1, -1)
						.split(',')
						.join(' | ');
					return `Omit<${expression.arguments[0].getText(tree)}, ${keys}>`;
				}
				return expression.getText(tree);
			}),
		);
		interfaceFiles.push(file);
		interfaces.push(
			`// Backend: dto/${file}\nexport interface ${node.name.text}${
				parent?.length ? ' extends ' + parent.join(', ') : ''
			} {\n${fields.join('\n')}\n}`,
		);
	}
}
const interfaceNames = interfaces.map((text) => text.match(/export interface (\w+)/)[1]);
const modules = [...new Set(interfaceFiles)];
for (const file of modules) {
	const target = path.join(destination, file);
	fs.mkdirSync(path.dirname(target), { recursive: true });
	const own = interfaces.filter((_, index) => interfaceFiles[index] === file);
	const ownNames = own.map((text) => text.match(/export interface (\w+)/)[1]);
	const body = own.join('\n\n');
	const mentions = (names) => names.filter((name) => new RegExp('\\b' + name + '\\b').test(body));
	let enumPath = path.relative(path.dirname(target), path.join(enumDestination, 'index')).replace(/\\/g, '/');
	let typePath = path.relative(path.dirname(target), path.join(destination, 'contracts')).replace(/\\/g, '/');
	if (!enumPath.startsWith('.')) enumPath = './' + enumPath;
	if (!typePath.startsWith('.')) typePath = './' + typePath;
	const enumRefs = mentions(enumNames),
		typeRefs = mentions(interfaceNames.filter((name) => !ownNames.includes(name)));
	const imports =
		(enumRefs.length ? `import { ${enumRefs.join(', ')} } from '${enumPath}';\n` : '') +
		(typeRefs.length ? `import type { ${typeRefs.join(', ')} } from '${typePath}';\n` : '');
	fs.writeFileSync(
		target,
		'// Generated by scripts/sync-backend-contracts.cjs. GraphQL IDs and timestamps are strings.\n' +
			imports +
			'\n' +
			body +
			'\n',
	);
}
fs.writeFileSync(
	path.join(destination, 'contracts.ts'),
	'// Generated contract exports.\n' +
		modules.map((file) => `export * from './${file.replace(/\.ts$/, '')}';`).join('\n') +
		'\n',
);
console.log(`Generated ${interfaces.length} interfaces and ${enumNames.length} enums by domain.`);
